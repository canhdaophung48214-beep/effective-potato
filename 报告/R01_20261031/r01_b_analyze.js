'use strict';
const fs = require('fs');
const path = require('path');
const RAW = path.join(__dirname, '_raw');
const records = JSON.parse(fs.readFileSync(path.join(RAW, 'records.json'), 'utf8'));
const blockers = JSON.parse(fs.readFileSync(path.join(RAW, 'blockers.json'), 'utf8'));
const idmap = JSON.parse(fs.readFileSync(path.join(RAW, 'idmap_probe.json'), 'utf8'));
const recs = records.records;
const ents = blockers.entries;
const out = {};
const tally = (arr, f) => { const m = {}; for (const x of arr) { const k = f(x) == null ? 'null' : String(f(x)); m[k] = (m[k] || 0) + 1; } return m; };

out.recordsTotal = recs.length;
out.blockersTotal = ents.length;
out.blockerCountField = blockers.count;
out.recordTopKeys = Object.keys(recs[0]).sort();
out.genKeys = Object.keys(recs[0].gen).sort();
out.sampleRecord = JSON.stringify(recs[0], null, 1);
out.sampleBlocker = JSON.stringify(ents[0], null, 1);
out.sampleBlockerC = JSON.stringify(ents.find(e => e.tier === 'C'), null, 1);
out.byTier = tally(recs, r => r.gen.tier);
out.byGen = tally(recs, r => r.gen.generation_status);
out.byEvidence = tally(recs, r => r.gen.evidence_status);
out.byElig = tally(recs, r => r.gen.import_eligibility);
out.byIdStatus = tally(recs, r => r.gen.id_status);
out.crossTierId = tally(recs, r => r.gen.tier + '|' + r.gen.id_status);
out.crossTierEvidence = tally(recs, r => r.gen.tier + '|' + r.gen.evidence_status);
out.blockerKind = tally(ents, e => e.kind);
out.blockerTier = tally(ents, e => e.tier);
out.blockerReasonCodes = tally(ents, e => (e.reasons || []).join('+') || '(none)');
out.reasonCodeSingle = tally(ents.flatMap(e => e.reasons || []), x => x);
out.blockerStall = tally(ents, e => (e.stallId || '(none)') + '|' + (e.tier || ''));
out.recordStall = tally(recs, r => (r.stallId || '(none)') + '|' + (r.gen ? r.gen.tier : '?'));
out.genBlockerTag = tally(recs.flatMap(r => r.gen.blockers || []), x => x);
out.blockerKeyPrefix = tally(ents, e => String(e.recordKey).split('|')[0] ? 'hasPipe' : 'noPipe');
out.idsNull = recs.filter(r => r.id === null).length;
out.idRange = (() => { const v = recs.map(r => r.id).filter(x => x !== null); return { n: v.length, min: Math.min(...v), max: Math.max(...v), uniq: new Set(v).size }; })();
out.idmapKeys = idmap.topKeys;
out.idmapSample = idmap.sample;
out.idmapBytes = idmap.bytes;
out.kenNames = (() => { const nul = recs.filter(r => r.name == null || r.name === ''); return { emptyName: nul.length }; })();
out.priceShape = tally(recs, r => typeof r.price);
out.dupeKeys = (() => { const m = {}; for (const e of ents) m[e.recordKey] = (m[e.recordKey] || 0) + 1; return Object.values(m).filter(x => x > 1).length; })();
out.blockersNotInRecords = (() => { const names = new Set(recs.map(r => r.stallId + '|' + r.name)); return ents.filter(e => !names.has(e.stallId + '|' + e.name)).length; })();
fs.writeFileSync(path.join(RAW, 'b_analysis.json'), JSON.stringify(out, null, 2) + '\n', 'utf8');
const brief = Object.assign({}, out);
delete brief.sampleRecord; delete brief.sampleBlocker; delete brief.sampleBlockerC;
console.log(JSON.stringify(brief, null, 1));
