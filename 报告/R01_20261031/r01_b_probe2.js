'use strict';
const fs = require('fs'); const path = require('path');
const PROJ = "C:\\Users\\25975\\Desktop\\食神寻味小程序开发\\项目";
const rd = p => fs.readFileSync(path.join(PROJ, p), 'utf8');
const out = {};
const ap = JSON.parse(rd('tools/pilot/approvals/ap-20261025-01.json'));
out.approvalKeys = Object.keys(ap);
out.approval = JSON.stringify(ap).slice(0, 1200);
const map = JSON.parse(rd('tools/pilot/id-map.json'));
out.mapInit = JSON.stringify(map.initialization);
out.mapKeyFormat = map.keyFormat;
out.mapEntries = map.entries.length;
out.mapStatuses = [...new Set(map.entries.map(e => e.status))];
out.mapOrphans = JSON.stringify(map.orphans).slice(0, 300);
out.mapStalls = [...new Set(map.entries.map(e => e.stallId))].sort();
out.mapStallCounts = map.entries.reduce((m, e) => (m[e.stallId] = (m[e.stallId] || 0) + 1, m), {});
const c = rd('docs/RECORD_GENERATOR_CONTRACT_20261023.md');
const lines = c.split(/\r?\n/);
out.contractLines = lines.length;
const hits = (needle) => lines.map((l, i) => [i + 1, l]).filter(([i, l]) => l.indexOf(needle) >= 0).slice(0, 6);
for (const k of ['名册位次', '3F 编号', 'candidate_only', 'E11_', 'import_eligibility']) out['grep_' + k] = hits(k).map(([i, l]) => i + ': ' + l.slice(0, 150));
// roster table lines
const ridx = lines.map((l, i) => [i, l]).filter(([i, l]) => l.indexOf('名册位次') >= 0 || l.indexOf('3F 编号') >= 0).map(([i]) => i);
out.rosterHeaderLines = ridx.map(i => i + 1);
out.rosterSample = ridx.length ? lines.slice(ridx[0] - 3, ridx[0] + 4).join('\n') : '';
const dec = fs.readdirSync(path.join(PROJ, 'docs', 'decisions'));
out.decisions = dec;
out.decAdmission = dec.filter(f => /ADMISSION|admission|准入/.test(f));
console.log(JSON.stringify(out, null, 1).slice(0, 6500));
